ALIGN = {'l': WD_ALIGN_PARAGRAPH.LEFT, 'c': WD_ALIGN_PARAGRAPH.CENTER,
         'r': WD_ALIGN_PARAGRAPH.RIGHT, 'j': WD_ALIGN_PARAGRAPH.JUSTIFY}


def new_doc(landscape=False):
    doc = Document()
    st = doc.styles['Normal']
    st.font.name = '宋体'
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    sec = doc.sections[0]
    if landscape:
        sec.page_width, sec.page_height = Cm(29.7), Cm(21)
    else:
        sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2.2)
    sec.top_margin = Cm(2.0)
    sec.bottom_margin = Cm(1.8)
    return doc


def _font(run, font, size, bold=False):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font)


def para(doc, text, size=10.5, font='宋体', bold=False, align='l', space_after=4, indent=False):
    p = doc.add_paragraph()
    p.alignment = ALIGN[align]
    p.paragraph_format.space_after = Pt(space_after)
    if indent:
        p.paragraph_format.first_line_indent = Pt(21)
    _font(p.add_run(text), font, size, bold)
    return p


def title(doc, text, size=16):
    para(doc, text, size=size, font='黑体', bold=True, align='c', space_after=2)


def subtitle(doc, text, size=10.5):
    para(doc, text, size=size, font='楷体', align='c', space_after=6)


def cell(c, text, bold=False, size=10.5, align='l', font='宋体'):
    c.text = ''
    p = c.paragraphs[0]
    p.alignment = ALIGN[align]
    p.paragraph_format.space_after = Pt(0)
    _font(p.add_run(text), font, size, bold)


def build_table(doc, rows, widths=None):
    """rows: 列表元素为
       ('r', [c1..cn])            普通行
       ('h', 行高cm, '文本')       整行合并 + 指定行高（用于大段填写区）
       ('m', '文本')               整行合并普通高度
    """
    ncols = 4
    for r in rows:
        if r[0] == 'r':
            ncols = len(r[1])
            break
    table = doc.add_table(rows=0, cols=ncols)
    table.style = 'Table Grid'
    for r in rows:
        row = table.add_row()
        if r[0] == 'r':
            for i, v in enumerate(r[1]):
                bold = isinstance(v, tuple) and v[1]
                txt = v[0] if isinstance(v, tuple) else v
                cell(row.cells[i], txt, bold=bold, align='c' if bold else 'l')
        else:
            h, txt = r[1], r[2]
            merged = row.cells[0].merge(row.cells[ncols - 1])
            cell(merged, txt, align='l')
            if h:
                row.height = Cm(h)
                row.height_rule = WD_ROW_HEIGHT_RULE.AT_LEAST
    if widths:
        for row in table.rows:
            for i, w in enumerate(widths):
                if i < len(row.cells):
                    row.cells[i].width = Cm(w)
    return table


def notes(doc, lines, head='填表说明：'):
    para(doc, head, size=9.5, font='黑体', bold=True, space_after=2)
    for i, t in enumerate(lines, 1):
        para(doc, str(i) + '. ' + t, size=9, space_after=1)


