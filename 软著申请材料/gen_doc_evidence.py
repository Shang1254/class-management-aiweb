def expand():
    lines = []
    for kind, text in C:
        if kind == 'blank':
            lines.append('')
        elif kind == 'h1':
            lines.append('')
            lines.append(text)
            lines.append('')
        elif kind == 'h2':
            lines.append('')
            lines.append(text)
        elif kind == 'li':
            wrapped = wrap_line(text, WRAP_AT - 2)
            lines.append('· ' + wrapped[0])
            for w in wrapped[1:]:
                lines.append('  ' + w)
        else:
            lines.extend(wrap_line(text))
    return lines


def main():
    lines = expand()
    total_pages = (len(lines) + LINES_PER_PAGE - 1) // LINES_PER_PAGE
    doc = new_doc(line_pt=14, font='宋体', size=10.5, margins=(2.4, 2.2, 2.4, 2.4))
    set_header_footer(doc, '软件说明书（文档鉴别材料）')

    fixed_line(doc, NAME_VER, size=14, bold=True)
    fixed_line(doc, '软件说明书（文档鉴别材料）', size=12, bold=True)
    fixed_line(doc, '编制日期：' + DATE + '    文档页数：共 %d 页（每页 30 行）' % (total_pages + 3), size=9)
    fixed_line(doc, '')

    for i in range(0, len(lines), LINES_PER_PAGE):
        chunk = lines[i:i + LINES_PER_PAGE]
        for ln in chunk:
            fixed_line(doc, ln, size=10.5, bold=ln.strip().startswith('第') and '章' in ln,
                       line_pt=14)
        for _ in range(LINES_PER_PAGE - len(chunk)):
            fixed_line(doc, '', line_pt=14)
        if i + LINES_PER_PAGE < len(lines):
            doc.add_page_break()

    doc.save(OUT)
    print('软件说明书（文档鉴别材料）已生成 ->', OUT)
    print('  正文 %d 行 / %d 页（每页 %d 行）' % (len(lines), total_pages, LINES_PER_PAGE))
    print('  文件大小：%.1f KB' % (os.path.getsize(OUT) / 1024))


if __name__ == '__main__':
    main()
