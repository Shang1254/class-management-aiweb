def bullet(doc, text, size=11):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Pt(22)
    p.paragraph_format.space_after = Pt(3)
    _font(p.add_run('· ' + text), '宋体', size)


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = 'Table Grid'
    for i, htxt in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ''
        p = c.paragraphs[0]
        p.alignment = ALIGN['c']
        _font(p.add_run(htxt), '黑体', 10, True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            _font(p.add_run(str(v)), '宋体', 9.5)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                if i < len(r.cells):
                    r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def compress(src_dir, dst_dir, max_w=1100, quality=85):
    os.makedirs(dst_dir, exist_ok=True)
    out = {}
    for name in sorted(os.listdir(src_dir)):
        if not name.lower().endswith('.png'):
            continue
        im = Image.open(os.path.join(src_dir, name)).convert('RGB')
        if im.width > max_w:
            im = im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)
        dst = os.path.join(dst_dir, os.path.splitext(name)[0] + '.jpg')
        im.save(dst, 'JPEG', quality=quality, optimize=True)
        out[name] = dst
    return out


def figure(doc, imgs, shot_name, caption, width_cm=15.5):
    path = imgs.get(shot_name)
    if not path:
        para(doc, '（截图缺失：' + shot_name + '）', align='c', color=(0xC0, 0x00, 0x00))
        return
    p = doc.add_paragraph()
    p.alignment = ALIGN['c']
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(3)
    p.add_run().add_picture(path, width=Cm(width_cm))
    cp = doc.add_paragraph()
    cp.alignment = ALIGN['c']
    cp.paragraph_format.space_after = Pt(10)
    _font(cp.add_run(caption), '楷体', 9)


